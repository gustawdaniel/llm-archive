def _slugify(text: str) -> str:
    clean = re.sub(r"[^\w\s-]", "", text.lower())
    return re.sub(r"[-\s]+", "-", clean).strip("-")[:80] or "temat"

TOPIC_NAMING_SYSTEM_PROMPT = """Jesteś precyzyjnym asystentem, który nazywa kategorię tematyczną na podstawie tytułów kilku rozmów, które automatyczny klasyfikator uznał za pokrewne.
Zaproponuj JEDNĄ krótką (2-4 słowa) nazwę tematu w języku polskim, oddającą ich wspólny mianownik.
Zasady:
- Ignoruj tytuły generyczne/bezsensowne (np. "New chat", "Rozmowa ChatGPT", surowe URL) - skup się na tych, które niosą treść.
- Zwróć WYŁĄCZNIE samą nazwę tematu, bez cudzysłowów, bez markdownu, bez komentarzy."""


def _build_ollama_urls() -> List[str]:
    """Same candidate-endpoint logic as Embedder/AutoTitler (rog GPU -> mac GPU ->
    brain-db CPU fallback), duplicated here rather than imported since it's a tiny
    pure function and topic naming has no other dependency on Embedder's state."""
    raw_candidates: List[str] = []
    if settings.OLLAMA_BASE_URL:
        raw_candidates.append(settings.OLLAMA_BASE_URL)
    if settings.OLLAMA_FALLBACK_URLS:
        raw_candidates.extend(settings.OLLAMA_FALLBACK_URLS)
    else:
        raw_candidates.extend(settings.get_default_ollama_urls())

    seen = set()
    urls: List[str] = []
    for u in raw_candidates:
        clean = u.rstrip("/")
        if clean and clean not in seen:
            seen.add(clean)
            urls.append(clean)
    return urls


async def _name_topic_via_llm(sample_titles: List[str], model: Optional[str] = None) -> Optional[str]:
    """Synthesizes a short topic name from a sample of member conversation titles,
    instead of just copying one member's raw title (which is often itself
    uninformative - "New chat", a bare URL, generic UI-telemetry text)."""
    model = model or settings.TITLER_MODEL
    prompt = "Tytuły rozmów:\n" + "\n".join(f"- {t}" for t in sample_titles) + "\n\nNazwa tematu (2-4 słowa):"
    messages = [
        {"role": "system", "content": TOPIC_NAMING_SYSTEM_PROMPT},
        {"role": "user", "content": prompt},
    ]

    async with httpx.AsyncClient(timeout=60.0) as client:
        for url in _build_ollama_urls():
            try:
                resp = await client.post(
                    f"{url}/api/chat",
                    json={
                        "model": model,
                        "messages": messages,
                        "stream": False,
                        "options": {"temperature": 0.2, "num_predict": 20},
                    },
                )
                if resp.status_code == 200:
                    content = resp.json().get("message", {}).get("content", "").strip()
                    if content:
                        first_line = content.split("\n")[0].strip()
                        cleaned = first_line.strip(" \"'*_#")
                        if cleaned and _looks_like_polish_or_english(cleaned):
                            return cleaned[:80]
            except Exception as e:
                logger.debug(f"Topic naming via {url} failed: {e}")
                continue

    logger.warning("Topic naming via LLM failed on all Ollama endpoints - falling back to raw-title placeholder.")
    return None


DESCRIBE_SYSTEM_PROMPT = """Jesteś precyzyjnym analitykiem. Na podstawie próbki tytułów i realnych wypowiedzi użytkownika z kilku rozmów, które automatyczny klasyfikator uznał za tematycznie pokrewne, napisz krótki opis wspólnego tematu/projektu oraz słowa kluczowe.
Odpowiedz WYŁĄCZNIE w tym formacie, bez niczego innego:
OPIS: <2-3 zdania po polsku, konkretnie o czym są te rozmowy>
SŁOWA_KLUCZOWE: <5-8 konkretnych słów/fraz po polsku, oddzielonych przecinkami, bez ogólników typu "rozmowa" czy "pytanie">"""


def _looks_like_polish_or_english(text: str) -> bool:
    """qwen2.5 occasionally code-switches to Chinese output despite a Polish
    system prompt (seen in practice: a topic description came back entirely in
    Chinese). Rejects output where too much of it falls outside Latin script -
    cheap and sufficient, no need for a real language detector here."""
    if not text:
        return False
    letters = [c for c in text if c.isalpha()]
    if not letters:
        return False
    non_latin = sum(1 for c in letters if not ("a" <= c.lower() <= "z" or c in "ąćęłńóśźż"))
    return (non_latin / len(letters)) < 0.2


def _parse_description_response(raw: str) -> Tuple[Optional[str], Optional[List[str]]]:
    description = None
    keywords: Optional[List[str]] = None
    for line in raw.splitlines():
        line = line.strip()
        upper = line.upper()
        if upper.startswith("OPIS:"):
            description = line.split(":", 1)[1].strip() or None
        elif upper.startswith("SŁOWA_KLUCZOWE:") or upper.startswith("SLOWA_KLUCZOWE:"):
            raw_kw = line.split(":", 1)[1].strip()
            keywords = [k.strip() for k in raw_kw.split(",") if k.strip()] or None
    return description, keywords


async def _describe_topic_via_llm(
    sample_titles: List[str], sample_messages: List[str], model: Optional[str] = None
) -> Tuple[Optional[str], Optional[List[str]]]:
    """One deeper LLM call per topic (not per conversation) - pooled real user
    messages from several member conversations, not just their titles. Cheap in
    aggregate since there are only ~30-60 topics, unlike per-conversation calls."""
    model = model or settings.TITLER_MODEL
    parts = ["Tytuły rozmów w tym temacie:"] + [f"- {t}" for t in sample_titles]
    if sample_messages:
        parts.append("\nPróbka wypowiedzi użytkownika z tych rozmów:")
        parts.extend(f"- {m}" for m in sample_messages)

    messages = [
        {"role": "system", "content": DESCRIBE_SYSTEM_PROMPT},
        {"role": "user", "content": "\n".join(parts)},
    ]

    async with httpx.AsyncClient(timeout=90.0) as client:
        for url in _build_ollama_urls():
            try:
                resp = await client.post(
                    f"{url}/api/chat",
                    json={
                        "model": model,
                        "messages": messages,
                        "stream": False,
                        "options": {"temperature": 0.2, "num_predict": 350},
                    },
                )
                if resp.status_code == 200:
                    content = resp.json().get("message", {}).get("content", "").strip()
                    if content and _looks_like_polish_or_english(content):
                        return _parse_description_response(content)
            except Exception as e:
                logger.debug(f"Topic description via {url} failed: {e}")
                continue

    logger.warning("Topic description via LLM failed on all Ollama endpoints.")
    return None, None


SAME_TOPIC_SYSTEM_PROMPT = """Oceniasz wynik automatycznej klasteryzacji rozmów. Dostajesz dwa tematy (nazwa + opis + słowa kluczowe) i masz ocenić, czy opisują FAKTYCZNIE TEN SAM temat/projekt, a nie tylko podobną kategorię ogólną (np. "poprawa gramatyki" i "tłumaczenie na angielski" to NIE to samo, mimo że obie są o języku).
Odpowiedz WYŁĄCZNIE jednym słowem: TAK albo NIE."""


async def _topics_are_same_via_llm(topic_a: Dict[str, Any], topic_b: Dict[str, Any], model: Optional[str] = None) -> bool:
    model = model or settings.TITLER_MODEL

    def _fmt(t: Dict[str, Any]) -> str:
        kw = ", ".join(t.get("keywords") or [])
        return f"Nazwa: {t['name']}\nOpis: {t.get('description') or '(brak)'}\nSłowa kluczowe: {kw or '(brak)'}"

    prompt = f"Temat A:\n{_fmt(topic_a)}\n\nTemat B:\n{_fmt(topic_b)}\n\nCzy to ten sam temat?"
    messages = [
        {"role": "system", "content": SAME_TOPIC_SYSTEM_PROMPT},
        {"role": "user", "content": prompt},
    ]

    async with httpx.AsyncClient(timeout=60.0) as client:
        for url in _build_ollama_urls():
            try:
                resp = await client.post(
                    f"{url}/api/chat",
                    json={
                        "model": model,
                        "messages": messages,
                        "stream": False,
                        "options": {"temperature": 0.0, "num_predict": 5},
                    },
                )
                if resp.status_code == 200:
                    content = resp.json().get("message", {}).get("content", "").strip().upper()
                    if content:
                        return content.startswith("TAK")
            except Exception as e:
                logger.debug(f"Same-topic judge via {url} failed: {e}")
                continue

    logger.warning("Same-topic LLM judge failed on all Ollama endpoints - treating as 'different' (no merge).")
    return False


def _representative_text(row: Dict[str, Any], user_messages: Optional[List[str]] = None) -> str:
    """Title + summary (if the Qwen backfill ever populates it) + a handful of
    real user messages sampled across the WHOLE conversation (head/middle/tail,
    via the same sample_user_messages used for auto-titling) - not just its
    opening. Two failed attempts before this one: chunk_index=0 alone is pure
    Title/Platform/Model/Tools boilerplate, zero conversation content, so
    conversations sharing an opening (e.g. ChatGPT UI branches/regenerations
    that diverge later) look identical no matter how different they become.
    The first two real turns (chunk_index 1,2) - i.e. still only the opening -
    collapsed clustering into one blob (long/noisy tool-call and code
    boilerplate drowns the topic signal). Sampling short snippets from
    throughout the conversation, verified empirically on live data: no blob
    collapse, and markedly more specific clusters (e.g. "SPF/DKIM/DMARC email"
    and "rezydencja podatkowa Paragwaj" instead of a vague "Konfiguracja i
    problemy techniczne" grab-bag)."""
    parts = [f"Title: {row['title']}"]
    if row.get("summary"):
        parts.append(row["summary"])
    if user_messages:
        parts.extend(sample_user_messages(user_messages, max_samples=4, max_chars_per_msg=150))
    elif row.get("overview_text"):
        parts.append(row["overview_text"])
    return "\n".join(parts)


def _normalize(vec: np.ndarray) -> np.ndarray:
    norm = np.linalg.norm(vec)
    return vec / norm if norm > 0 else vec


GENERIC_TITLES = {"new chat", "untitled", "rozmowa", "nowa rozmowa", "new conversation", "chatgpt", "gemini"}


def _is_generic_title(title: str) -> bool:
    return (title or "").strip().lower() in GENERIC_TITLES


def _split_oversized_clusters(
    matrix: np.ndarray,
    labels: np.ndarray,
    probabilities: np.ndarray,
    max_cluster_size: int,
    min_cluster_size: int,
    max_rounds: int = 3,
) -> tuple:
    """A single flat HDBSCAN pass finds a few tight micro-clusters plus one or two
    huge, semantically incoherent ones (e.g. "Integracja API" absorbing Rust
    benchmarks, dotfiles, and Google Maps key security alike) - real structure
    that's invisible at the scale of the whole dataset, dense in a genuinely
    balanced way. Re-running HDBSCAN on JUST an oversized cluster's members finds
    that finer structure, since density is relative to the point set given to it.
    Members that don't resolve into a sub-cluster stay under the original
    (broader) label rather than becoming outliers - no coverage is lost.

    Uses a SMALLER min_cluster_size for the recursive pass than the top-level
    one: empirically, re-running at the same min_cluster_size on an already
    oversized cluster found nothing (0 sub-clusters on a 160-member blob at
    min_cluster_size=5) - a niche of 3-5 out of 160 is just as meaningful as
    5 out of 3733 was at the top level, so the bar should relax with depth.
    """
    labels = labels.copy()
    probabilities = probabilities.copy()
    sub_min_cluster_size = max(2, min_cluster_size - 2)

    for _ in range(max_rounds):
        cluster_ids = sorted(set(int(l) for l in labels if l != -1))
        oversized = [cl for cl in cluster_ids if int((labels == cl).sum()) > max_cluster_size]
        if not oversized:
            break

        next_label = max(cluster_ids) + 1
        any_split = False

        for cl in oversized:
            idx = np.where(labels == cl)[0]
            sub_clusterer = HDBSCAN(min_cluster_size=sub_min_cluster_size, metric="cosine")
            sub_labels = sub_clusterer.fit_predict(matrix[idx])
            sub_probs = getattr(sub_clusterer, "probabilities_", np.ones(len(sub_labels)))

            sub_cluster_ids = sorted(set(int(l) for l in sub_labels if l != -1))
            if not sub_cluster_ids:
                continue  # no finer structure found - leave this cluster as-is

            any_split = True
            for sub_cl in sub_cluster_ids:
                member_mask = sub_labels == sub_cl
                global_idx = idx[member_mask]
                labels[global_idx] = next_label
                probabilities[global_idx] = sub_probs[member_mask]
                next_label += 1
            # sub-clustering noise (-1) keeps the original, broader label `cl`

        if not any_split:
            break

    return labels, probabilities


class TopicClusterer:
    def __init__(
        self,
        db: Database,
        embedder: Embedder,
        min_cluster_size: int = 5,
        max_cluster_size: int = 40,
        match_threshold: float = 0.85,
        similarity_threshold: float = 0.75,
        top_k_neighbors: int = 5,
    ):
        self.db = db
        self.embedder = embedder
        self.min_cluster_size = min_cluster_size
        self.max_cluster_size = max_cluster_size
        self.match_threshold = match_threshold
        self.similarity_threshold = similarity_threshold
        self.top_k_neighbors = top_k_neighbors

    async def ensure_embeddings(self, force: bool = False) -> int:
        """Computes llm_conversations.embedding for conversations that don't have
        one yet (or all of them, with force=True - e.g. after summaries land)."""
        rows = await self.db.get_conversation_topic_texts(only_missing_embedding=not force)
        if not rows:
            return 0

        ids = [r["id"] for r in rows]
        msgs_by_conv = await self.db.get_user_messages_for_conversations(ids, limit_per_conv=30)
        texts = [_representative_text(r, msgs_by_conv.get(r["id"])) for r in rows]
        embeddings = await self.embedder.embed_texts(texts)
        await self.db.update_conversation_embeddings(list(zip(ids, embeddings)))
        return len(rows)

    async def recluster(self) -> Dict[str, Any]:
        """HDBSCAN over every conversation with an embedding, matched against
        existing topics by centroid similarity so names/descriptions persist."""
        conv_rows = await self.db.get_all_conversation_embeddings()
        if len(conv_rows) < self.min_cluster_size:
            return {"conversations": len(conv_rows), "clusters": 0, "assigned": 0, "outliers": len(conv_rows)}

        ids = [r["id"] for r in conv_rows]
        matrix = np.array([r["embedding"] for r in conv_rows], dtype=np.float64)

        clusterer = HDBSCAN(min_cluster_size=self.min_cluster_size, metric="cosine")
        labels = clusterer.fit_predict(matrix)
        probabilities = getattr(clusterer, "probabilities_", np.ones(len(labels)))

        labels, probabilities = _split_oversized_clusters(
            matrix, labels, probabilities,
            max_cluster_size=self.max_cluster_size,
            min_cluster_size=self.min_cluster_size,
        )

        existing_topics = await self.db.get_topics()
        cluster_labels = sorted(set(int(l) for l in labels if l != -1))

        cluster_to_topic_id: Dict[int, Any] = {}
        matched_topic_ids = set()
        new_topics = 0

        for cl in cluster_labels:
            member_idx = np.where(labels == cl)[0]
            centroid = _normalize(matrix[member_idx].mean(axis=0))

            best_topic = None
            best_score = -1.0
            for t in existing_topics:
                if t["id"] in matched_topic_ids:
                    continue
                t_centroid = _normalize(np.array(t["centroid"], dtype=np.float64))
                score = float(np.dot(centroid, t_centroid))
                if score > best_score:
                    best_score = score
                    best_topic = t

            if best_topic is not None and best_score >= self.match_threshold:
                cluster_to_topic_id[cl] = best_topic["id"]
                matched_topic_ids.add(best_topic["id"])
                await self.db.update_topic_centroid(best_topic["id"], centroid.tolist())
            else:
                ranked_members = member_idx[np.argsort(-probabilities[member_idx])][:10]
                top_ids = [conv_rows[i]["id"] for i in ranked_members]
                top_titles = [conv_rows[i]["title"] for i in ranked_members]

                generic_ids = [cid for cid, t in zip(top_ids, top_titles) if _is_generic_title(t)]
                snippets = await self.db.get_conversation_snippets(generic_ids) if generic_ids else {}

                sample_titles = [
                    (snippets.get(cid) or title)[:200] if _is_generic_title(title) else title
                    for cid, title in zip(top_ids, top_titles)
                ]

                name = await _name_topic_via_llm(sample_titles)
                if not name:
                    best_member = member_idx[int(np.argmax(probabilities[member_idx]))]
                    name = f"Nowy temat: {conv_rows[best_member]['title'][:60]}"
                topic_id = await self.db.create_topic(name, centroid.tolist())
                cluster_to_topic_id[cl] = topic_id
                new_topics += 1
                # Deliberately NOT appended to `existing_topics` for this same
                # run: tried that (matching two clusters created in the same
                # pass against each other, e.g. "Poprawa gramatyki" and
                # "Poprawka gramatyczna" at 0.93), and it caused a chain
                # reaction - cluster A absorbs B, A's centroid drifts toward B,
                # that drifted centroid now matches C too, drifts further,
                # matches D... reconstituting a 55-member "Problem chłodzenia
                # sprzętu" grab-bag under a new misleading name, the same
                # failure mode the recursive split exists to prevent, just via
                # a different path. Cross-topic deduping only happens
                # explicitly and safely via merge_similar_topics()/`topics
                # merge-similar`, which never mutates a centroid mid-pass.

        assignments = []
        for idx, label in enumerate(labels):
            if label == -1:
                continue
            assignments.append((ids[idx], cluster_to_topic_id[int(label)], float(probabilities[idx])))

        await self.db.replace_auto_topic_assignments(ids, assignments)
        await self.db.mark_conversations_clustered(ids)

        return {
            "conversations": len(ids),
            "clusters": len(cluster_to_topic_id),
            "new_topics": new_topics,
            "matched_topics": len(matched_topic_ids),
            "assigned": len(assignments),
            "outliers": int((labels == -1).sum()),
        }

    async def generate_descriptions(self, only_missing: bool = True, sample_size: int = 6) -> int:
        """Populates llm_topics.description/keywords from a deeper sample than
        naming uses: real pooled user messages across several member
        conversations, not just titles. Also the input the gray-zone merge
        pass (merge_similar_topics) judges on."""
        topics = await self.db.get_topics_with_descriptions()
        targets = [t for t in topics if not only_missing or not t.get("description")]
        updated = 0

        for t in targets:
            members = await self.db.get_topic_conversations(t["id"], limit=sample_size)
            if not members:
                continue

            member_ids = [uuid.UUID(m["id"]) for m in members]
            titles = [m["title"] for m in members]
            msgs_by_conv = await self.db.get_user_messages_for_conversations(member_ids, limit_per_conv=4)

            pooled_messages = []
            for cid in member_ids:
                for msg in (msgs_by_conv.get(cid) or [])[:4]:
                    cleaned = (msg or "").strip()
                    if cleaned:
                        pooled_messages.append(cleaned[:400])

            description, keywords = await _describe_topic_via_llm(titles, pooled_messages)
            if description or keywords:
                await self.db.update_topic_description(t["id"], description, keywords)
                updated += 1

        return updated

    async def merge_similar_topics(self, low_threshold: float = 0.6, high_threshold: Optional[float] = None) -> int:
        """The ONLY cross-topic dedup mechanism (see recluster()'s comment on why
        automatic same-run centroid merging was tried and reverted - it chain-
        reacted into new grab-bag topics). Every topic pair with centroid cosine
        similarity in [low_threshold, high_threshold] gets an LLM judgment call
        on name+description+keywords rather than trusting the raw number either
        way - this covers BOTH the "should've obviously merged" range (>0.85,
        e.g. "Poprawa gramatyki"/"Poprawka gramatyczna" at 0.93) and the gray
        zone a pure threshold misses (e.g. "Zabezpieczenie"/"Bezpieczeństwo API"
        at 0.73). No centroid mutation happens here, so no chain reaction is
        possible - each pair is judged independently against its ORIGINAL
        centroid similarity. Requires descriptions - run generate_descriptions
        first or pairs without one just get skipped (no signal to judge on)."""
        high = high_threshold if high_threshold is not None else 1.01
        topics = await self.db.get_topics_with_descriptions()
        merged = 0
        alive = {t["id"]: t for t in topics if t.get("description")}
        ids = list(alive.keys())

        for i in range(len(ids)):
            id_a = ids[i]
            if id_a not in alive:
                continue
            for j in range(i + 1, len(ids)):
                id_b = ids[j]
                if id_b not in alive:
                    continue
                a, b = alive[id_a], alive[id_b]
                ca = _normalize(np.array(a["centroid"], dtype=np.float64))
                cb = _normalize(np.array(b["centroid"], dtype=np.float64))
                sim = float(np.dot(ca, cb))
                if not (low_threshold <= sim < high):
                    continue

                same = await _topics_are_same_via_llm(a, b)
                if same:
                    await self.db.merge_topic(id_a, id_b)
                    del alive[id_b]
                    merged += 1

        return merged

    # --- Manual curation: user picks a name, attaches conversations they like,
    # gets similarity-based suggestions for what else might belong. Auto-
    # clustering (recluster()) never touches source='manual' rows, so this
    # coexists safely with it - see docs/topics_knowledge_graph.md. ---

    async def create_manual_topic(self, name: str, description: Optional[str] = None) -> Any:
        # No members yet, so no real centroid - a zero vector is a harmless
        # placeholder (cosine similarity against it is meaningless until
        # recompute_topic_centroid runs after the first assignment).
        placeholder_centroid = [0.0] * 1024
        return await self.db.create_topic(name, placeholder_centroid, description=description, is_manual=True)

    async def assign(self, topic_id: Any, conversation_id: Any, source: str = "manual") -> None:
        await self.db.assign_conversation_to_topic(conversation_id, topic_id, score=1.0, source=source)
        await self.recompute_topic_centroid(topic_id)

    async def unassign(self, topic_id: Any, conversation_id: Any) -> bool:
        removed = await self.db.unassign_conversation_from_topic(conversation_id, topic_id)
        if removed:
            await self.recompute_topic_centroid(topic_id)
        return removed

    async def recompute_topic_centroid(self, topic_id: Any) -> None:
        embeddings = await self.db.get_topic_member_embeddings(topic_id)
        if not embeddings:
            return
        matrix = np.array(embeddings, dtype=np.float64)
        centroid = _normalize(matrix.mean(axis=0))
        await self.db.update_topic_centroid(topic_id, centroid.tolist())

    async def suggest(self, topic_id: Any, limit: int = 10) -> list:
        return await self.db.suggest_similar_conversations(topic_id, limit=limit)

    async def export_similarity_edges(self) -> int:
        return await self.db.compute_and_store_similarity_edges(
            top_k=self.top_k_neighbors, min_score=self.similarity_threshold
        )

    async def export_similarity_links_to_markdown(self, markdown_root: Path) -> int:
        """Injects a delimited '## Related' wikilink block into each conversation's
        exported markdown file, so Obsidian's native graph view renders the
        similarity graph for free. Idempotent: re-running replaces the block.

        Known limitation (see ClickUp task 869f70wa1): a normal `ingest`/
        `import-takeout` run regenerates the whole file from the normalizer and
        does NOT know about this block - re-run this command after any bulk
        re-ingest to restore the links.
        """
        rows = await self.db.get_conversations_with_similarity_edges()
        updated = 0

        for row in rows:
            rel_path = row.get("relative_path")
            if not rel_path:
                continue
            file_path = markdown_root / rel_path
            if not file_path.exists():
                continue

            content = file_path.read_text(encoding="utf-8")
            lines = [RELATED_BEGIN, "## Related (podobieństwo semantyczne, nie cytowania)"]
            for n in row["neighbors"]:
                if not n.get("relative_path"):
                    continue
                target = n["relative_path"]
                if target.endswith(".md"):
                    target = target[:-3]
                title = (n.get("title") or target).replace("|", "-").replace("[", "").replace("]", "")
                lines.append(f"- [[{target}|{title}]] (podobieństwo: {n['score']:.2f})")
            lines.append(RELATED_END)
            block = "\n".join(lines)

            if RELATED_BEGIN in content:
                pre, _, rest = content.partition(RELATED_BEGIN)
                _, _, post = rest.partition(RELATED_END)
                new_content = pre.rstrip() + "\n\n" + block + post
            else:
                new_content = content.rstrip() + "\n\n" + block + "\n"

            if new_content != content:
                file_path.write_text(new_content, encoding="utf-8")
                updated += 1

        return updated

    async def export_hub_docs(self, markdown_root: Path) -> int:
        """One markdown file per topic in <markdown_root>/_topics/ - a "Map of
        Content" hub, not a conversation: name, keywords (as Obsidian #tags, so
        topics sharing a keyword connect in Obsidian's own tag graph for free),
        an explicit "Powiązane tematy" cross-link list (topics sharing >=1
        keyword, computed here rather than relying only on the tag graph, since
        explicit wikilinks are what actually shows as edges in Obsidian's note
        graph view), and a linked list of member conversations.

        Everything is inside a delimited block so re-running this (e.g. after
        recluster/describe/merge-similar changes names, keywords or membership)
        only replaces that block - anything the user writes below survives.
        These files live in the same Syncthing-synced vault as conversation
        notes, so refreshing them here is what actually propagates a DB-side
        change (rename, re-tag, merge) out to Obsidian on other machines.
        """
        topics = await self.db.get_topics_with_descriptions()
        hub_dir = markdown_root / "_topics"
        hub_dir.mkdir(parents=True, exist_ok=True)

        kw_by_topic = {t["id"]: set(k.lower() for k in (t.get("keywords") or [])) for t in topics}
        updated = 0

        for t in topics:
            members = await self.db.get_topic_conversations_with_paths(t["id"])
            my_keywords = kw_by_topic[t["id"]]

            related = []
            if my_keywords:
                for other in topics:
                    if other["id"] == t["id"]:
                        continue
                    overlap = my_keywords & kw_by_topic[other["id"]]
                    if overlap:
                        related.append((len(overlap), other))
                related.sort(key=lambda x: -x[0])

            slug = _slugify(t["name"])
            file_path = hub_dir / f"{slug}.md"

            lines = [HUB_BEGIN, f"# {t['name']}", ""]
            if t.get("description"):
                lines.append(t["description"])
                lines.append("")
            if t.get("keywords"):
                lines.append(" ".join(f"#{_slugify(k).replace('-', '_')}" for k in t["keywords"]))
                lines.append("")

            if related:
                lines.append("## Powiązane tematy")
                for _, other in related[:8]:
                    other_slug = _slugify(other["name"])
                    lines.append(f"- [[_topics/{other_slug}|{other['name']}]]")
                lines.append("")

            lines.append(f"## Konwersacje ({len(members)})")
            for m in members:
                if not m.get("relative_path"):
                    continue
                target = m["relative_path"]
                if target.endswith(".md"):
                    target = target[:-3]
                title = (m.get("title") or target).replace("|", "-").replace("[", "").replace("]", "")
                lines.append(f"- [[{target}|{title}]]")
            lines.append(HUB_END)
            block = "\n".join(lines)

            if file_path.exists():
                content = file_path.read_text(encoding="utf-8")
                if HUB_BEGIN in content:
                    pre, _, rest = content.partition(HUB_BEGIN)
                    _, _, post = rest.partition(HUB_END)
                    new_content = pre + block + post
                else:
                    new_content = block + "\n\n" + content
            else:
                new_content = block + "\n"

            if not file_path.exists() or file_path.read_text(encoding="utf-8") != new_content:
                file_path.write_text(new_content, encoding="utf-8")
                updated += 1

        return updated
